"""Factor complexity and block entropy of the zigzag coding of Recaman's sequence.

A sequence generated by a substitution (or any morphic / Sturmian-like rule) has factor
complexity p(n) = O(n) and block entropy H(n) = O(log n), so the entropy increments
h(n) = H(n+1) - H(n) tend to 0. A sequence with positive topological entropy has p(n) growing
exponentially and h(n) settling at a positive value. This script measures both for several
codings of the zigzag phases printed by `recaman_fast --dump`, and for control sequences.

usage: python3 complexity.py zz_dump.txt [maxn]
"""
import sys
import numpy as np

MASK = np.uint64(0xFFFFFFFFFFFFFFFF)


def factor_stats(seq, maxn):
    """p(n) and H(n) (bits) for n = 1..maxn, using rolling 64-bit polynomial hashes."""
    seq = np.asarray(seq, dtype=np.uint64) + np.uint64(1)
    base = np.uint64(1000003)
    h = np.zeros(len(seq), dtype=np.uint64)
    out = []
    with np.errstate(over="ignore"):
        for n in range(1, maxn + 1):
            # h[i] = hash of seq[i : i + n]
            h = h[: len(seq) - n + 1] * base + seq[n - 1 :]
            _, counts = np.unique(h, return_counts=True)
            p = counts / counts.sum()
            out.append((n, len(counts), float(-(p * np.log2(p)).sum())))
    return out


def report(name, seq, maxn):
    stats = factor_stats(seq, maxn)
    print(f"\n== {name}: length {len(seq)}, alphabet {len(set(seq[:1000000]))}")
    print("   n      p(n)   p(n)/n     H(n)   h(n)=H(n+1)-H(n)")
    for i, (n, p, H) in enumerate(stats):
        hn = stats[i + 1][2] - H if i + 1 < len(stats) else float("nan")
        if n <= 10 or n % 5 == 0:
            print(f"{n:4d} {p:9d} {p / n:8.1f} {H:8.3f}   {hn:7.4f}")
    return stats


def fib_word(length):
    a, b = "0", "01"
    while len(b) < length:
        a, b = b, b + a
    return [int(c) for c in b[:length]]


def thue_morse(length):
    return [bin(i).count("1") % 2 for i in range(length)]


def markov_surrogate(seq, rng):
    """Order-1 Markov chain with the empirical transition matrix of seq."""
    seq = np.asarray(seq)
    k = seq.max() + 1
    T = np.zeros((k, k))
    np.add.at(T, (seq[:-1], seq[1:]), 1)
    T = T / np.maximum(T.sum(1, keepdims=True), 1)
    cum = T.cumsum(1)
    out = np.empty(len(seq), dtype=np.int64)
    out[0] = seq[0]
    u = rng.random(len(seq))
    for i in range(1, len(seq)):
        out[i] = min(np.searchsorted(cum[out[i - 1]], u[i]), k - 1)
    return out


def main():
    path = sys.argv[1]
    maxn = int(sys.argv[2]) if len(sys.argv) > 2 else 40
    lev, typ, m = [], [], []
    with open(path) as f:
        for line in f:
            parts = dict(tok.split("=", 1) for tok in line.split() if "=" in tok)
            lev.append(int(float(parts["x/k"])))
            typ.append(1 if " jump " in line else 0)
            m.append(int(parts["m"]))
    lev, typ, m = np.array(lev), np.array(typ), np.array(m)

    # Codings of each zigzag phase.
    c_type = typ                                   # jump or full drain
    c_lev_type = lev * 2 + typ                     # level and type
    jcap = np.where(typ == 1, np.minimum(m, 3), 4) # jump index 0,1,2,3+, or 4 = full drain
    c_lev_type_j = lev * 5 + jcap                  # level, type and capped jump index

    rng = np.random.default_rng(1)
    N = len(c_type)
    report("CONTROL Fibonacci word (substitution)", fib_word(N), maxn)
    report("CONTROL Thue-Morse (substitution)", thue_morse(N), maxn)
    report("Recaman: jump/full", c_type, maxn)
    report("CONTROL i.i.d. shuffle of jump/full", rng.permutation(c_type), maxn)
    report("Recaman: (level, jump/full)", c_lev_type, maxn)
    report("CONTROL Markov-1 surrogate of (level, jump/full)", markov_surrogate(c_lev_type, rng), maxn)
    report("Recaman: (level, jump/full, jump index capped at 3)", c_lev_type_j, maxn)


if __name__ == "__main__":
    main()
